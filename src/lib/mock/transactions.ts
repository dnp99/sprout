function txn(
  id: string,
  merchant: string,
  emoji: string,
  categoryId: string,
  categoryName: string,
  amountCents: number,
  dateLabel: string,
  timeLabel: string,
  method: string,
  note: string,
): Transaction {
  return {
    id: `t_${id}`,
    merchant,
    emoji,
    categoryId,
    categoryName,
    amountCents,
    note,
    method,
    status: "posted",
    dateLabel,
    timeLabel,
    occurredAt: "",
    isIncome: false,
  };
}

